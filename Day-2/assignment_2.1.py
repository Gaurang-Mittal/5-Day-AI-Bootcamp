import numpy as np

# 1D array (1-dimensional data)
data_1d = np.random.randint(1, 100, size=5)
print("1D Array:")
print(data_1d)

# 2D array (2-dimensional data)
data_2d = np.random.randint(1, 100, size=(3, 4))
print("\n2D Array:")
print(data_2d)

# 3D array (3-dimensional data)
data_3d = np.random.randint(1, 100, size=(2, 3, 4))
print("\n3D Array:")
print(data_3d)